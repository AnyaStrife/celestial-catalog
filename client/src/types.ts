// List of supported celestial object types.
export const CELESTIAL_TYPES = [
  "star",
  "planet",
  "galaxy",
  "nebula",
  "black_hole",
] as const;

// Derive the type from the list to keep the allowed values consistent.
export type CelestialType = (typeof CELESTIAL_TYPES)[number];

// Readable labels used to display each type in the UI.
export const TYPE_LABELS: Record<CelestialType, string> = {
  star: "Étoile",
  planet: "Planète",
  galaxy: "Galaxie",
  nebula: "Nébuleuse",
  black_hole: "Trou noir",
};

// Represents a celestial object returned by the API.
export type CelestialObject = {
  id: number;
  name: string;
  type: CelestialType;
  constellation: string | null;
  distanceLightYears: number;
  observed: boolean;
  createdAt: string;
};

// Input data excludes fields generated by the backend.
export type CelestialObjectInput = Omit<CelestialObject, "id" | "createdAt">;
